import requests
import pandas as pd
import os
from urllib.parse import quote_plus
from sqlalchemy import create_engine



def extract(players):
    rows = []
    for p in players:
        response = requests.get("https://lichess.org/api/user/" + p)
        if response.status_code != 200:
            print("skipping", p, response.status_code)
            continue
        data = response.json()
        rows.append({
            "username": data["username"],
            "blitz": data["perfs"]["blitz"]["rating"],
            "bullet": data["perfs"]["bullet"]["rating"],
            "blitz_games": data["perfs"]["blitz"]["games"],
        })
    return pd.DataFrame(rows)

def transform(df):
    df=df[df["blitz_games"] > 100]
    df=df[df['bullet']!=1500]
    return df

def load(df):
    password = quote_plus(os.environ["MYSQL_PASSWORD"])
    engine = create_engine(f"mysql+pymysql://root:{password}@localhost:3306/chess_db")
    df.to_sql("players", engine, if_exists="replace", index=False)

players = ["DrNykterstein", "penguingim1", "Fins", "nihalsarin2004", "Alireza2003", "lichess"]

raw = extract(players)
clean = transform(raw)
load(clean)
print("loaded", len(clean), "rows")
print(clean)